def _rows(text: str, first_cell: str) -> list[str]:
    rows = [line for line in text.splitlines() if line.startswith(f"| {first_cell} |")]
    assert rows, f"no table row starting with {first_cell}"
    return rows


def _row(text: str, first_cell: str) -> str:
    return _rows(text, first_cell)[0]


def _cells(row: str) -> list[str]:
    """Cells of one table row (``\\|`` inside a cell is not a separator)."""
    assert row.startswith("| ")
    assert row.endswith(" |")
    return re.split(r"(?<!\\) \| ", row[2:-2])


def _section(text: str, heading: str) -> str:
    """The lines after ``heading`` up to the next heading (fenced code blocks skipped)."""
    lines = text.splitlines()
    start = lines.index(heading) + 1
    fence = ""
    for end in range(start, len(lines)):
        line = lines[end]
        if fence:
            fence = "" if line == fence else fence
        elif opening := re.match(r"`{3,}", line):
            fence = opening.group()
        elif line.startswith("#"):
            return "\n".join(lines[start:end])
    return "\n".join(lines[start:])


def _docstring(obj: object) -> str:
    """A docstring as the reference quotes it: cleaned, no trailing blanks on any line."""
    doc = inspect.cleandoc(getattr(obj, "__doc__", None) or "")
    return "\n".join(line.rstrip() for line in doc.splitlines())


def _primary_commands(
    parser: argparse.ArgumentParser,
) -> dict[str, tuple[argparse.ArgumentParser, list[str]]]:
    """``{command: (parser, aliases)}``: argparse registers a command before its aliases."""
    subs = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    names: dict[int, list[str]] = {}
    parsers: dict[int, argparse.ArgumentParser] = {}
    for name, child in subs._name_parser_map.items():
        names.setdefault(id(child), []).append(name)
        parsers[id(child)] = child
    return {found[0]: (parsers[key], found[1:]) for key, found in names.items()}



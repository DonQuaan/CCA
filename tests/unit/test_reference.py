# --- environment variables
ENV_SOURCE = '''
import os
from os import environ, getenv

A = os.environ.get("MOD_LEVEL")


def outer():
    """Outer summary.

    More text.
    """
    def inner():
        return os.getenv("INNER")
    return inner


class C:
    def m(self, key):
        """Method summary."""
        os.environ["WRITTEN"] = "1"
        x = environ["READ"]
        y = "PRESENT" in os.environ
        z = getenv(key)
        w = os.environ.copy()
        os.environ.setdefault("DEFAULTED", "1")
        v = "ABSENT" not in environ
        return os.environ.pop("POPPED", None)


class Settings:
    """A class docstring is not a function summary."""

    HOME = os.environ.get("CLASS_LEVEL")
'''


def test_env_reads_find_every_access_form(gen: ModuleType) -> None:
    got = {
        r.name: (r.where, r.function, r.access, r.summary)
        for r in gen.env_reads(ENV_SOURCE, "x.py")
    }
    assert got == {
        "MOD_LEVEL": ("x.py", "<module>", "environ.get()", ""),
        "INNER": ("x.py", "outer.inner", "getenv()", ""),
        "WRITTEN": ("x.py", "C.m", "environ[...] (write)", "Method summary."),
        "READ": ("x.py", "C.m", "environ[...]", "Method summary."),
        "PRESENT": ("x.py", "C.m", "in environ", "Method summary."),
        "<dynamic: key>": ("x.py", "C.m", "getenv()", "Method summary."),
        "DEFAULTED": ("x.py", "C.m", "environ.setdefault()", "Method summary."),
        "ABSENT": ("x.py", "C.m", "in environ", "Method summary."),
        "POPPED": ("x.py", "C.m", "environ.pop()", "Method summary."),
        "CLASS_LEVEL": ("x.py", "Settings", "environ.get()", ""),
    }
    lines = {r.name: r.line for r in gen.env_reads(ENV_SOURCE, "x.py")}
    assert lines["MOD_LEVEL"] == 5



def test_committed_reference_documents_every_cli_command_and_flag(committed: str) -> None:
    commands = _primary_commands(build_parser())
    assert commands
    for name, (parser, aliases) in commands.items():
        section = _section(committed, f"### `cca {name}`")
        for alias in aliases:  # folded into the command, never a heading of its own
            assert f"`{alias}`" in section
            assert f"### `cca {alias}`" not in committed.splitlines()
        if parser.epilog:
            assert " ".join(parser.epilog.split()) in html.unescape(section)
        for action in parser._actions:
            if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
                continue
            flag = ", ".join(action.option_strings) or str(action.metavar or action.dest)
            cells = _cells(_row(section, f"`{flag}`"))
            assert cells[1].startswith(_expected_kind(action)), (flag, cells)
            if action.required:
                assert cells[2] == "*required*"
            elif isinstance(action.default, _SCALARS) and action.default != argparse.SUPPRESS:
                assert cells[2] == f"`{action.default!r}`", cells
            if isinstance(action.type, FunctionType) and action.type.__closure__:
                # a type made by a factory shows the values it captured
                bound = inspect.getclosurevars(action.type).nonlocals
                assert all(f"{k}={v!r}" in cells[1] for k, v in bound.items()), cells
            choices = ", ".join(f"`{c!r}`" for c in action.choices or ())
            assert cells[3] == choices, (flag, cells)
            assert _unescape_cell(cells[4]) == _expected_help(parser, action), (flag, cells)


def _expected_kind(action: argparse.Action) -> str:
    """The start of an argument's Type cell: flag, str, a class name or a return annotation."""
    if action.nargs == 0:
        return "flag"
    if action.type is None:
        return "str"
    if isinstance(action.type, FunctionType):
        returns = inspect.signature(action.type).return_annotation
        if returns is not inspect.Signature.empty:
            return returns if isinstance(returns, str) else returns.__name__
    return str(getattr(action.type, "__name__", ""))


def _expected_help(parser: argparse.ArgumentParser, action: argparse.Action) -> str:
    if action.help is None:
        return ""
    if action.help == argparse.SUPPRESS:
        return "(hidden from `--help`)"
    return " ".join(parser._get_formatter()._expand_help(action).split())


def _unescape_cell(cell: str) -> str:
    return html.unescape(cell.replace("\\|", "|"))


def _uci_lines() -> list[str]:
    out = io.StringIO()
    protocol.UciServer(stdin=io.StringIO("uci\nquit\n"), stdout=out).serve()
    return out.getvalue().splitlines()


def _uci_options() -> list[dict[str, str | list[str] | None]]:
    pattern = re.compile(
        r"option name (?P<name>.+?) type (?P<type>\S+)(?: default ?(?P<default>.*?))?"
        r"(?: min (?P<min>\S+))?(?: max (?P<max>\S+))?(?P<vars>(?: var .*?)*)"
    )
    found = []
    for line in _uci_lines():
        if line.startswith("option "):
            match = pattern.fullmatch(line)
            assert match is not None, line
            option: dict[str, str | list[str] | None] = dict(match.groupdict())
            option["vars"] = [v for v in (match["vars"] or "").split(" var ") if v]
            found.append(option)
    return found


def _code(value: str) -> str:
    assert "`" not in value
    return f"`{value}`" if value else "*(empty)*"


def test_committed_uci_rows_match_a_real_handshake(committed: str) -> None:
    options = _uci_options()
    assert options
    helps = getattr(protocol, "UCI_OPTION_HELP", {})
    section = _section(committed, "## 4. UCI options")
    for option in options:
        name, default, low, high, values = (
            option[k] for k in ("name", "default", "min", "max", "vars")
        )
        assert isinstance(name, str)
        cells = _cells(_row(section, f"`{name}`"))
        expected = [_code(v) if isinstance(v, str) else "" for v in (default, low, high)]
        assert cells[1:5] == [option["type"], *expected], cells
        assert isinstance(values, list)
        assert cells[5] == ", ".join(_code(v) for v in values), cells
        help_text = " ".join(helps.get(name, "").split())
        assert html.unescape(cells[6].replace("\\|", "|")) == help_text
    rows = [line for line in section.splitlines() if line.startswith("| `")]
    documented = [_cells(row)[0] for row in rows if len(_cells(row)) == 7]
    assert documented == [f"`{o['name']}`" for o in options]  # in the advertised order
    for line in _uci_lines():
        if line.startswith("id "):
            key, _, value = line[3:].partition(" ")
            assert f"| `{key}` | `{value}` |" in section.splitlines(), line
    placeholders = sorted(getattr(protocol, "_PLACEHOLDERS", ()))
    if placeholders:
        shown = ", ".join(f"`{p}`" for p in placeholders)
        assert f"Default placeholders that mean *unset*: {shown}." in section


def _public_dataclasses() -> list[type[Any]]:
    """Every public top-level dataclass in ``src/cca``, found by a text scan of the sources."""
    found: list[type[Any]] = []
    decorated = re.compile(
        r"^@(?:dataclasses\.)?dataclass\b.*\n(?:@.*\n)*class (\w+)", re.MULTILINE
    )
    for path in sorted((ROOT / "src" / "cca").rglob("*.py")):
        names = [n for n in decorated.findall(path.read_text(encoding="utf-8")) if n[0] != "_"]
        if names:
            parts = path.relative_to(ROOT / "src").with_suffix("").parts
            module = importlib.import_module(".".join(p for p in parts if p != "__init__"))
            found.extend(getattr(module, n) for n in names)
    return found


def _field_docs(cls: type[Any]) -> dict[str, str]:
    """``{field: attribute docstring}`` from the class source, whitespace folded."""
    tree = ast.parse(textwrap.dedent(inspect.getsource(cls)))
    body = next(n for n in tree.body if isinstance(n, ast.ClassDef)).body
    docs = {}
    for stmt, after in itertools.pairwise([*body, None]):
        if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
            value = None
            if isinstance(after, ast.Expr) and isinstance(after.value, ast.Constant):
                value = after.value.value
            docs[stmt.target.id] = " ".join(value.split()) if isinstance(value, str) else ""
    return docs


def _same_annotation(cell: str, annotation: object) -> bool:
    written = cell.replace("\\|", "|").removeprefix("`").removesuffix("`")
    if not isinstance(annotation, str):  # a module without ``from __future__ import annotations``
        return bool(written)
    dump = [ast.dump(ast.parse(a, mode="eval")) for a in (written, annotation)]
    return dump[0] == dump[1]


def test_committed_dataclass_tables_match_every_field(committed: str) -> None:
    classes = _public_dataclasses()
    assert set(CONFIG_CLASSES) <= set(classes)
    model = importlib.import_module("cca.core.types")
    in_model = [c for c in classes if c.__module__ == model.__name__]
    assert in_model
    assert set(in_model) == {
        c for c in vars(model).values() if isinstance(c, type) and dataclasses.is_dataclass(c)
    }
    for cls in classes:
        section = _section(committed, f"### `{cls.__name__}`")
        assert section.lstrip("\n").startswith(f"`{cls.__module__}.{cls.__qualname__}`")
        annotations: dict[str, object] = {}
        for klass in reversed(cls.__mro__):
            annotations.update(inspect.get_annotations(klass))
        docs = _field_docs(cls)
        rows = [line for line in section.splitlines() if line.startswith("| `")]
        fields = dataclasses.fields(cls)
        assert [_cells(row)[0] for row in rows] == [f"`{f.name}`" for f in fields], cls
        for row, f in zip(rows, fields, strict=True):
            cells = _cells(row)
            assert _same_annotation(cells[1], annotations[f.name]), (cls, f.name, cells)
            assert _unescape_cell(cells[3]) == docs.get(f.name, ""), (cls, f.name, cells)
            if f.default is dataclasses.MISSING:
                if f.default_factory is dataclasses.MISSING:
                    assert cells[2] == "*required*", (cls, f.name)
            elif isinstance(f.default, _SCALARS):
                assert cells[2] == f"`{f.default!r}`", (cls, f.name, cells)


def _changed(value: object) -> int | float:
    """A value of the same type that differs from a numeric default (to load real TOML)."""
    if isinstance(value, int):
        return value + 1
    assert isinstance(value, float)
    return value / 2 if value else 0.5


def test_committed_config_file_sections_load_as_documented(committed: str, tmp_path: Path) -> None:
    section = _section(committed, "### Configuration file")
    assert _docstring(config.load_agent_config) in section
    assert _docstring(config) in section
    by_name = {cls.__name__: cls for cls in CONFIG_CLASSES}
    documented: dict[str, type[Any]] = {}
    for row in section.splitlines():
        match = re.fullmatch(r"\| `\[(\w+)\]` \| `(\w+)` \|", row)
        if match:
            documented[match[1]] = by_name[match[2]]
    assert documented
    for name, cls in documented.items():
        label = _section(committed, f"### `{cls.__name__}`").lstrip("\n").splitlines()[0]
        assert f"`[{name}]`" in label, (name, label)
        field, default = next(
            (f.name, f.default)
            for f in dataclasses.fields(cls)
            if isinstance(f.default, (int, float)) and not isinstance(f.default, bool)
        )
        path = tmp_path / f"{name}.toml"
        new = _changed(default)
        path.write_text(f"[{name}]\n{field} = {json.dumps(new)}\n", encoding="utf-8")
        loaded = config.load_agent_config(path)
        owner = loaded if cls is AgentConfig else getattr(loaded, name)
        assert isinstance(owner, cls)
        assert getattr(owner, field) == new, (name, field)
    for cls in set(CONFIG_CLASSES) - set(documented.values()):
        label = _section(committed, f"### `{cls.__name__}`").lstrip("\n").splitlines()[0]
        assert "TOML section" not in label, label
    # Every name the loader accepts is documented (an unknown section is a ConfigError).
    candidates = {*documented, *(f.name for f in dataclasses.fields(AgentConfig))}
    candidates |= {"agent", "config", "engine", "chaos", "ar1", "baseline", "cca"}
    candidates |= {cls.__name__.lower() for cls in CONFIG_CLASSES}
    accepted = set()
    for name in sorted(candidates):
        path = tmp_path / f"probe_{name}.toml"
        path.write_text(f"[{name}]\n", encoding="utf-8")
        try:
            config.load_agent_config(path)
        except config.ConfigError:
            continue
        accepted.add(name)
    assert accepted == set(documented)
    preset = tmp_path / "preset.toml"
    persona = list_personas()[-1]
    preset.write_text(f'[persona]\npreset = "{persona}"\n', encoding="utf-8")
    assert config.load_agent_config(preset).persona == config.load_persona(persona)


